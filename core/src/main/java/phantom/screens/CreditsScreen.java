package phantom.screens;

import com.badlogic.gdx.graphics.Color;

import phantom.PhantomGame;
import phantom.input.GameAction;
import phantom.util.Constants;

/**
 * Credits overlay.
 * <p>OOP concept: simple overlay screen.</p>
 */
public final class CreditsScreen extends BaseScreen {
    private static final Color TEXT = new Color(0.9f, 0.92f, 0.96f, 1f);
    private static final Color DIM = new Color(0.62f, 0.66f, 0.74f, 1f);
    private static final String[] LINES = {
        "A college object-oriented programming project",
        "",
        "Design, code and procedural art - the Phantom team",
        "Engine - libGDX (Apache License 2.0)",
        "Typeface - Liberation Serif (SIL Open Font License 1.1)",
        "Every sprite, background and sound is generated by code at startup.",
        "",
        "Inspired by the moody hand-drawn metroidvanias we love.",
        "All characters, places and words are original."
    };
    private float time;

    public CreditsScreen(PhantomGame game) {
        super(game);
    }

    @Override
    public void update(float dt) {
        time += dt;
        if (time > 0.2f && (game.input().isJustPressed(GameAction.CONFIRM) || game.input().isJustPressed(GameAction.BACK))) {
            game.screens().pop();
        }
    }

    @Override
    public void render(float alpha, float frameDelta) {
        float a = Math.min(1f, time * 4f);
        game.beginUi();
        game.batch().begin();
        game.ui().rect(0, 0, Constants.UI_WIDTH, Constants.UI_HEIGHT, 0f, 0f, 0.01f, 0.85f * a);
        float cx = Constants.UI_WIDTH / 2f;
        game.ui().centered(game.fonts().large(), "Credits", cx, 600, TEXT, a);
        game.ui().ornament(cx, 535, 360, a);
        for (int i = 0; i < LINES.length; i++) {
            game.ui().centered(game.fonts().small(), LINES[i], cx, 480 - i * 34, i == 0 ? TEXT : DIM, a);
        }
        game.ui().centered(game.fonts().small(), "Enter / Esc to return", cx, 70, DIM, a * 0.7f);
        game.batch().end();
    }

    @Override
    public boolean isOverlay() { return true; }
}
