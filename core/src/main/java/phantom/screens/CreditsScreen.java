package phantom.screens;

import com.badlogic.gdx.graphics.Color;

import phantom.PhantomGame;
import phantom.input.GameAction;
import phantom.util.Constants;

/**
 * Credits overlay: the team and who built which part of the game, then the tools and licences.
 * <p>OOP concept: simple overlay screen; a private record holds each team member's credit line.</p>
 */
public final class CreditsScreen extends BaseScreen {
    private static final Color TEXT = new Color(0.9f, 0.92f, 0.96f, 1f);
    private static final Color DIM = new Color(0.62f, 0.66f, 0.74f, 1f);
    private static final Color GOLD = new Color(1f, 0.85f, 0.6f, 1f);

    /** One team member: name, roll number, module and the main parts they built. */
    private record Member(String name, String roll, String module, String... work) { }

    private static final Member[] TEAM = {
        new Member("Abhinav Singh", "2501200022", "Core engine, player and movement",
                "Game loop and class hierarchy", "Player, abilities and input",
                "Collision, camera, rendering, sound", "Autoplay: jump prediction, routes"),
        new Member("Aryaman Gora", "2501200024", "Enemies, bosses and combat",
                "Enemy AI state machines", "Three bosses and their attacks",
                "Combat, particles, lighting, art", "Autoplay: combat planner"),
        new Member("Aarav Singh", "2501200016", "World, saving, screens and UI",
                "Rooms, level loader and validator", "Saving, events, story and endings",
                "Menus, HUD, NPCs and the shop", "Autoplay: quest planner, menu mode"),
    };
    private static final String[] FOOTER = {
        "Engine - libGDX (Apache License 2.0)   -   Typeface - Liberation Serif (SIL Open Font License 1.1)",
        "Every sprite, background and sound is generated by code at startup.",
        "Inspired by the moody hand-drawn metroidvanias we love. All characters, places and words are original."
    };
    private float time;

    public CreditsScreen(PhantomGame game) {
        super(game);
    }

    @Override
    public void update(float dt) {
        time += dt;
        if (time > 0.2f && (game.input().isJustPressed(GameAction.CONFIRM) || game.input().isJustPressed(GameAction.BACK))) {
            game.screens().pop();
        }
    }

    @Override
    public void render(float alpha, float frameDelta) {
        float a = Math.min(1f, time * 4f);
        game.beginUi();
        game.batch().begin();
        game.ui().rect(0, 0, Constants.UI_WIDTH, Constants.UI_HEIGHT, 0f, 0f, 0.01f, 0.96f * a);
        float cx = Constants.UI_WIDTH / 2f;
        game.ui().centered(game.fonts().large(), "Credits", cx, 652, TEXT, a);
        game.ui().ornament(cx, 592, 360, a);
        game.ui().centered(game.fonts().italic(), "A college object-oriented programming project, submitted to Dr. Gargi Singh",
                cx, 566, DIM, a);
        float column = Constants.UI_WIDTH / TEAM.length;
        for (int i = 0; i < TEAM.length; i++) {
            Member m = TEAM[i];
            float x = column * (i + 0.5f);
            game.ui().centered(game.fonts().medium(), m.name(), x, 502, GOLD, a);
            game.ui().centered(game.fonts().small(), m.roll(), x, 466, DIM, a);
            game.ui().centered(game.fonts().small(), m.module(), x, 432, TEXT, a);
            for (int k = 0; k < m.work().length; k++) {
                game.ui().centered(game.fonts().small(), m.work()[k], x, 396 - k * 28, DIM, a);
            }
        }
        game.ui().centered(game.fonts().small(), "Together: game design, playtesting and the project report", cx, 262, TEXT, a);
        game.ui().ornament(cx, 236, 260, a * 0.7f);
        for (int i = 0; i < FOOTER.length; i++) {
            game.ui().centered(game.fonts().small(), FOOTER[i], cx, 204 - i * 30, DIM, a);
        }
        game.ui().centered(game.fonts().small(), "Enter / Esc to return", cx, 52, DIM, a * 0.7f);
        game.batch().end();
    }

    @Override
    public boolean isOverlay() { return true; }
}
